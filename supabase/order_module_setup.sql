-- TK Sales Management: SKU catalogue and order-making tables
-- Safe to run in the existing Supabase project. Does not modify existing tables.

create table if not exists public.skus (
  id uuid primary key default gen_random_uuid(),
  sku_code text unique,
  category text not null,
  product_name text not null,
  product_size text not null,
  pieces_per_carton integer not null check (pieces_per_carton > 0),
  carton_rate numeric(12,2) not null check (carton_rate >= 0),
  per_piece_rate numeric(14,6) generated always as (carton_rate / pieces_per_carton) stored,
  active boolean not null default true,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sales_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  outlet_id uuid not null references public.outlets(id),
  area_id uuid not null references public.areas(id),
  created_by uuid not null references auth.users(id),
  order_date date not null default (now() at time zone 'Asia/Dhaka')::date,
  total_pieces integer not null default 0 check (total_pieces >= 0),
  gross_value numeric(14,2) not null default 0 check (gross_value >= 0),
  discount_amount numeric(14,2) not null default 0 check (discount_amount >= 0),
  net_value numeric(14,2) not null default 0 check (net_value >= 0),
  paid_amount numeric(14,2) not null default 0 check (paid_amount >= 0),
  balance_amount numeric(14,2) not null default 0 check (balance_amount >= 0),
  status text not null default 'submitted' check (status in ('submitted','cancelled')),
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.sales_order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.sales_orders(id) on delete cascade,
  sku_id uuid not null references public.skus(id),
  category text not null,
  product_name text not null,
  product_size text not null,
  pieces_per_carton integer not null check (pieces_per_carton > 0),
  carton_rate numeric(12,2) not null,
  per_piece_rate numeric(14,6) not null,
  carton_qty integer not null default 0 check (carton_qty >= 0),
  dozen_qty integer not null default 0 check (dozen_qty >= 0),
  piece_qty integer not null default 0 check (piece_qty >= 0),
  total_pieces integer not null default 0 check (total_pieces >= 0),
  free_pieces integer not null default 0 check (free_pieces >= 0),
  line_value numeric(14,2) not null default 0 check (line_value >= 0),
  created_at timestamptz not null default now()
);

create index if not exists idx_skus_active_category on public.skus(active, category, product_name);
create index if not exists idx_sales_orders_outlet_date on public.sales_orders(outlet_id, order_date desc);
create index if not exists idx_sales_orders_area_date on public.sales_orders(area_id, order_date desc);
create index if not exists idx_sales_orders_created_by on public.sales_orders(created_by, order_date desc);
create index if not exists idx_sales_order_items_order on public.sales_order_items(order_id);

alter table public.skus enable row level security;
alter table public.sales_orders enable row level security;
alter table public.sales_order_items enable row level security;

grant select on public.skus to authenticated;
grant insert, update, delete on public.skus to authenticated;
grant select, insert, update, delete on public.sales_orders to authenticated;
grant select, insert, update, delete on public.sales_order_items to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists "authenticated_read_active_skus" on public.skus;
create policy "authenticated_read_active_skus"
on public.skus for select to authenticated
using (active = true or exists (
  select 1 from public.profiles p
  where p.id = auth.uid() and p.role::text = 'RSM' and p.active = true
));

drop policy if exists "rsm_manage_skus" on public.skus;
create policy "rsm_manage_skus"
on public.skus for all to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role::text = 'RSM' and p.active = true))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role::text = 'RSM' and p.active = true));

drop policy if exists "role_read_scoped_sales_orders" on public.sales_orders;
create policy "role_read_scoped_sales_orders"
on public.sales_orders for select to authenticated
using (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.role::text = 'RSM' and p.active = true)
  or (created_by = auth.uid() and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role::text = 'SO' and p.active = true))
  or (area_id = (select p.area_id from public.profiles p where p.id = auth.uid() and p.role::text = 'ASM' and p.active = true))
);

drop policy if exists "so_asm_insert_own_sales_orders" on public.sales_orders;
create policy "so_asm_insert_own_sales_orders"
on public.sales_orders for insert to authenticated
with check (
  created_by = auth.uid()
  and exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.active = true
      and p.role::text in ('SO','ASM')
      and p.area_id = sales_orders.area_id
  )
  and exists (
    select 1 from public.outlets o
    where o.id = sales_orders.outlet_id and o.area_id = sales_orders.area_id and o.active = true
  )
);

drop policy if exists "rsm_manage_sales_orders" on public.sales_orders;
create policy "rsm_manage_sales_orders"
on public.sales_orders for all to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role::text = 'RSM' and p.active = true))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role::text = 'RSM' and p.active = true));

drop policy if exists "scoped_read_order_items" on public.sales_order_items;
create policy "scoped_read_order_items"
on public.sales_order_items for select to authenticated
using (exists (
  select 1 from public.sales_orders so
  where so.id = sales_order_items.order_id
));

drop policy if exists "so_asm_insert_order_items" on public.sales_order_items;
create policy "so_asm_insert_order_items"
on public.sales_order_items for insert to authenticated
with check (exists (
  select 1 from public.sales_orders so
  join public.profiles p on p.id = auth.uid()
  where so.id = sales_order_items.order_id
    and so.created_by = auth.uid()
    and p.active = true
    and p.role::text in ('SO','ASM')
));

drop policy if exists "rsm_manage_order_items" on public.sales_order_items;
create policy "rsm_manage_order_items"
on public.sales_order_items for all to authenticated
using (exists (
  select 1 from public.profiles p
  where p.id = auth.uid() and p.role::text = 'RSM' and p.active = true
))
with check (exists (
  select 1 from public.profiles p
  where p.id = auth.uid() and p.role::text = 'RSM' and p.active = true
));
