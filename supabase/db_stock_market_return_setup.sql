-- DB stock ledger + market returns + automatic secondary deduction
create table if not exists public.db_stock_movements (
 id uuid primary key default gen_random_uuid(),
 db_code text not null, db_name text not null, area_id uuid not null references public.areas(id),
 sku_id uuid not null references public.skus(id),
 movement_type text not null check (movement_type in ('opening','receipt','secondary','market_return','adjustment')),
 quantity_pieces integer not null check (quantity_pieces <> 0),
 reference_type text, reference_id uuid, unit_rate numeric(14,6) not null default 0,
 movement_value numeric(14,2) not null default 0,
 notes text, created_by uuid references auth.users(id), created_at timestamptz not null default now()
);
create index if not exists idx_db_stock_ledger_db_sku on public.db_stock_movements(db_code,sku_id,created_at);
create index if not exists idx_db_stock_ledger_area on public.db_stock_movements(area_id,created_at);
alter table public.db_stock_movements enable row level security;
grant select on public.db_stock_movements to authenticated;
drop policy if exists "read_scoped_db_stock_ledger" on public.db_stock_movements;
create policy "read_scoped_db_stock_ledger" on public.db_stock_movements for select to authenticated
using (
 exists(select 1 from public.profiles p where p.id=auth.uid() and p.active=true and p.role::text='RSM')
 or exists(select 1 from public.profiles p where p.id=auth.uid() and p.active=true and p.role::text='ASM' and p.area_id=db_stock_movements.area_id)
 or exists(select 1 from public.so_distributor_mappings m where m.so_profile_id=auth.uid() and m.active=true and m.db_code=db_stock_movements.db_code)
);
create table if not exists public.market_returns (
 id uuid primary key default gen_random_uuid(),
 return_number bigint generated by default as identity unique,
 so_profile_id uuid not null references public.profiles(id),
 area_id uuid not null references public.areas(id),
 db_code text not null, db_name text not null, return_date date not null default (now() at time zone 'Asia/Dhaka')::date,
 total_pieces integer not null default 0, total_value numeric(14,2) not null default 0,
 notes text, status text not null default 'submitted' check(status in ('submitted','cancelled')),
 created_at timestamptz not null default now()
);
create table if not exists public.market_return_items (
 id uuid primary key default gen_random_uuid(),
 return_id uuid not null references public.market_returns(id) on delete cascade,
 sku_id uuid not null references public.skus(id),
 product_name text not null, product_size text not null,
 quantity_pieces integer not null check(quantity_pieces>0),
 unit_rate numeric(14,6) not null, line_value numeric(14,2) not null,
 created_at timestamptz not null default now()
);
alter table public.market_returns enable row level security;
alter table public.market_return_items enable row level security;
grant select on public.market_returns, public.market_return_items to authenticated;
drop policy if exists "read_scoped_market_returns" on public.market_returns;
create policy "read_scoped_market_returns" on public.market_returns for select to authenticated
using (
 so_profile_id=auth.uid()
 or exists(select 1 from public.profiles p where p.id=auth.uid() and p.active=true and p.role::text='RSM')
 or exists(select 1 from public.profiles p where p.id=auth.uid() and p.active=true and p.role::text='ASM' and p.area_id=market_returns.area_id)
);
drop policy if exists "read_scoped_market_return_items" on public.market_return_items;
create policy "read_scoped_market_return_items" on public.market_return_items for select to authenticated
using(exists(select 1 from public.market_returns r where r.id=market_return_items.return_id));

-- Return reason and condition; damaged/expired quantities are not saleable stock.
alter table public.market_return_items add column if not exists return_reason text;
alter table public.market_return_items add column if not exists product_condition text not null default 'saleable';
alter table public.db_stock_movements drop constraint if exists db_stock_movements_movement_type_check;
alter table public.db_stock_movements add constraint db_stock_movements_movement_type_check
 check (movement_type in ('opening','receipt','secondary','market_return','market_return_damage','market_return_expired','adjustment'));

create or replace view public.db_stock_summary with (security_invoker=true) as
select m.db_code,m.db_name,m.area_id,m.sku_id,s.sku_code,s.product_name,s.product_size,s.category,
 coalesce(sum(case when m.movement_type in ('opening','receipt','secondary','market_return','adjustment') then m.quantity_pieces else 0 end),0)::bigint as stock_pieces,
 coalesce(sum(case when m.movement_type in ('opening','receipt','secondary','market_return','adjustment') then m.quantity_pieces else 0 end),0)::numeric / nullif(s.pieces_per_carton,0) as stock_cartons,
 coalesce(sum(case when m.movement_type in ('opening','receipt','secondary','market_return','adjustment') then m.movement_value else 0 end),0)::numeric(14,2) as net_stock_value,
 coalesce(sum(case when m.movement_type='market_return_damage' then m.quantity_pieces else 0 end),0)::bigint as damaged_stock_pieces,
 coalesce(sum(case when m.movement_type='market_return_expired' then m.quantity_pieces else 0 end),0)::bigint as expired_stock_pieces
from public.db_stock_movements m join public.skus s on s.id=m.sku_id
group by m.db_code,m.db_name,m.area_id,m.sku_id,s.sku_code,s.product_name,s.product_size,s.category,s.pieces_per_carton;
grant select on public.db_stock_summary to authenticated;

create or replace function public.record_secondary_stock_movement()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_order public.sales_orders%rowtype; v_map public.so_distributor_mappings%rowtype; v_sku public.skus%rowtype; v_qty integer;
begin
 select * into v_order from public.sales_orders where id=new.order_id;
 if v_order.status='cancelled' then return new; end if;
 if v_order.created_by is null then return new; end if;
 select * into v_map from public.so_distributor_mappings where so_profile_id=v_order.created_by and area_id=v_order.area_id and active=true;
 -- Do not block an order if mapping is missing or the order was entered by a non-SO user.
 -- Stock deduction is posted only when a valid active SO-to-DB mapping exists.
 if not found then return new; end if;
 select * into v_sku from public.skus where id=new.sku_id;
 v_qty:=coalesce(new.total_pieces,0)+coalesce(new.free_pieces,0);
 if v_qty>0 then
  insert into public.db_stock_movements(db_code,db_name,area_id,sku_id,movement_type,quantity_pieces,reference_type,reference_id,unit_rate,movement_value,created_by)
  values(v_map.db_code,v_map.db_name,v_map.area_id,new.sku_id,'secondary',-v_qty,'sales_order',new.order_id,
   coalesce(new.retailer_per_piece_rate,new.per_piece_rate,0),round(v_qty*coalesce(new.retailer_per_piece_rate,new.per_piece_rate,0),2),v_order.created_by);
 end if;
 return new;
end $$;
drop trigger if exists trg_order_item_secondary_stock on public.sales_order_items;
create trigger trg_order_item_secondary_stock after insert on public.sales_order_items
for each row execute function public.record_secondary_stock_movement();

create or replace function public.submit_market_return(p_return_date date,p_notes text,p_items jsonb)
returns uuid language plpgsql security definer set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_role text; v_area uuid; v_map public.so_distributor_mappings%rowtype;
 v_item jsonb; v_sku public.skus%rowtype; v_qty integer; v_sku_count integer; v_total integer:=0; v_value numeric(14,2):=0; v_id uuid; v_rate numeric(14,6); v_line numeric(14,2); v_reason text; v_condition text; v_movement text;
begin
 if v_uid is null then raise exception 'Login required'; end if;
 select role::text,area_id into v_role,v_area from public.profiles where id=v_uid and active=true;
 if v_role<>'SO' then raise exception 'শুধু SO Market Return Submit করতে পারবেন'; end if;
 select * into v_map from public.so_distributor_mappings where so_profile_id=v_uid and area_id=v_area and active=true;
 if not found then raise exception 'আপনার সক্রিয় DB Mapping পাওয়া যায়নি'; end if;
 if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception 'কমপক্ষে একটি SKU-এর ফেরত পরিমাণ দিন'; end if;
 for v_item in select value from jsonb_array_elements(p_items) loop
  v_qty:=greatest(coalesce((v_item->>'quantity_pieces')::integer,0),0);
  if v_qty=0 then continue; end if;
  select * into v_sku from public.skus where id=(v_item->>'sku_id')::uuid and active=true;
  if not found then raise exception 'একটি SKU পাওয়া যায়নি'; end if;
  select count(*) into v_sku_count from jsonb_array_elements(p_items) x where x->>'sku_id'=v_sku.id::text;
  if v_sku_count>1 then raise exception 'একই SKU একাধিকবার পাঠানো যাবে না'; end if;
  if not exists (
   select 1 from public.sales_orders so join public.sales_order_items soi on soi.order_id=so.id
   where so.created_by=v_uid and so.order_date=coalesce(p_return_date,(now() at time zone 'Asia/Dhaka')::date)
    and lower(coalesce(so.status,'submitted'))<>'cancelled' and soi.sku_id=v_sku.id
  ) then raise exception 'এই SKU নির্বাচিত দিনের অর্ডার সামারিতে নেই: %',v_sku.product_name; end if;
  v_reason:=coalesce(nullif(v_item->>'return_reason',''),'other');
  v_condition:=coalesce(nullif(v_item->>'product_condition',''),'saleable');
  if v_reason not in ('unsold','damaged','expired','packaging','wrong_supply','other') then raise exception 'রিটার্নের কারণ সঠিক নয়'; end if;
  if v_condition not in ('saleable','damaged','expired') then raise exception 'পণ্যের অবস্থা সঠিক নয়'; end if;
  v_rate:=coalesce(v_sku.retailer_per_piece_rate,v_sku.per_piece_rate,0);
  v_line:=round(v_qty*v_rate,2); v_total:=v_total+v_qty; v_value:=v_value+v_line;
 end loop;
 if v_total=0 then raise exception 'ফেরত পণ্যের পরিমাণ লিখুন'; end if;
 insert into public.market_returns(so_profile_id,area_id,db_code,db_name,return_date,total_pieces,total_value,notes)
 values(v_uid,v_area,v_map.db_code,v_map.db_name,coalesce(p_return_date,(now() at time zone 'Asia/Dhaka')::date),v_total,v_value,nullif(trim(coalesce(p_notes,'')),''))
 returning id into v_id;
 for v_item in select value from jsonb_array_elements(p_items) loop
  v_qty:=greatest(coalesce((v_item->>'quantity_pieces')::integer,0),0);
  if v_qty=0 then continue; end if;
  select * into v_sku from public.skus where id=(v_item->>'sku_id')::uuid and active=true;
  v_rate:=coalesce(v_sku.retailer_per_piece_rate,v_sku.per_piece_rate,0); v_line:=round(v_qty*v_rate,2);
  v_reason:=coalesce(nullif(v_item->>'return_reason',''),'other');
  v_condition:=coalesce(nullif(v_item->>'product_condition',''),'saleable');
  v_movement:=case v_condition when 'damaged' then 'market_return_damage' when 'expired' then 'market_return_expired' else 'market_return' end;
  insert into public.market_return_items(return_id,sku_id,product_name,product_size,quantity_pieces,unit_rate,line_value,return_reason,product_condition)
  values(v_id,v_sku.id,v_sku.product_name,v_sku.product_size,v_qty,v_rate,v_line,v_reason,v_condition);
  insert into public.db_stock_movements(db_code,db_name,area_id,sku_id,movement_type,quantity_pieces,reference_type,reference_id,unit_rate,movement_value,created_by)
  values(v_map.db_code,v_map.db_name,v_area,v_sku.id,v_movement,v_qty,'market_return',v_id,v_rate,v_line,v_uid);
 end loop;
 return v_id;
end $$;
revoke all on function public.submit_market_return(date,text,jsonb) from public;
grant execute on function public.submit_market_return(date,text,jsonb) to authenticated;

-- RSM-only opening/receipt/adjustment stock-in entry.
create or replace function public.post_db_stock_in(p_db_code text,p_movement_type text,p_sku_id uuid,p_quantity integer,p_notes text)
returns void language plpgsql security definer set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_role text; v_map public.so_distributor_mappings%rowtype; v_sku public.skus%rowtype; v_rate numeric(14,6);
begin
 select role::text into v_role from public.profiles where id=v_uid and active=true;
 if v_role<>'RSM' then raise exception 'শুধু RSM Opening/Receipt Stock Entry দিতে পারবেন'; end if;
 if p_movement_type not in ('opening','receipt','adjustment') or p_quantity<=0 then raise exception 'স্টক এন্ট্রির তথ্য সঠিক নয়'; end if;
 select * into v_map from public.so_distributor_mappings where db_code=p_db_code and active=true limit 1;
 if not found then raise exception 'Active DB Mapping পাওয়া যায়নি'; end if;
 select * into v_sku from public.skus where id=p_sku_id and active=true;
 if not found then raise exception 'SKU পাওয়া যায়নি'; end if;
 v_rate:=coalesce(v_sku.retailer_per_piece_rate,v_sku.per_piece_rate,0);
 insert into public.db_stock_movements(db_code,db_name,area_id,sku_id,movement_type,quantity_pieces,unit_rate,movement_value,notes,created_by)
 values(v_map.db_code,v_map.db_name,v_map.area_id,p_sku_id,p_movement_type,p_quantity,v_rate,round(p_quantity*v_rate,2),p_notes,v_uid);
end $$;
revoke all on function public.post_db_stock_in(text,text,uuid,integer,text) from public;
grant execute on function public.post_db_stock_in(text,text,uuid,integer,text) to authenticated;
